-- SmartFridge notifications schema hardening
-- Run this in Supabase SQL Editor after the base tables exist.

do $$
begin
  create type public.notification_type_enum as enum ('expiry', 'restock', 'recipe');
exception
  when duplicate_object then null;
end $$;

create table if not exists public.notifications (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id) on delete cascade,
  type public.notification_type_enum not null default 'expiry',
  ingredient_id integer references public.ingredients(id) on delete cascade,
  title varchar(200) not null,
  body text,
  is_read boolean not null default false,
  notification_date date not null default ((now() at time zone 'Asia/Taipei')::date),
  created_at timestamptz not null default now()
);

alter table public.notifications
  add column if not exists notification_date date;

update public.notifications
set notification_date = ((created_at at time zone 'Asia/Taipei')::date)
where notification_date is null;

alter table public.notifications
  alter column notification_date set default ((now() at time zone 'Asia/Taipei')::date),
  alter column notification_date set not null;

create unique index if not exists notifications_expiry_once_per_ingredient_day
on public.notifications (user_id, type, ingredient_id, notification_date)
where type = 'expiry' and ingredient_id is not null;

create index if not exists notifications_user_created_idx
on public.notifications (user_id, created_at desc);

create index if not exists notifications_user_unread_idx
on public.notifications (user_id, is_read, created_at desc);

alter table public.notifications enable row level security;

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.notifications to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists "notifications_owner_all" on public.notifications;

create policy "notifications_owner_all"
on public.notifications
for all
to authenticated
using (
  exists (
    select 1 from public.users u
    where u.id = notifications.user_id
      and u.auth_user_id = (select auth.uid())
  )
)
with check (
  exists (
    select 1 from public.users u
    where u.id = notifications.user_id
      and u.auth_user_id = (select auth.uid())
  )
);
